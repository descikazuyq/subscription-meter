// Package meter 提供本地运行的订阅、用量与账单能力。
//
// 使用 NewService（或可注入时钟的 NewServiceWithClock）得到一个并发安全的
// 内存服务，典型流程为：
//
//	s := meter.NewService()
//	_ = s.CreateAccount("acct-1")
//	_ = s.CreatePlan(meter.Plan{
//	    ID: "plan-1", MonthlyFee: 1000, IncludedUnits: 100,
//	    OveragePrice: 5, TaxRateBasisPoints: 600,
//	})
//	_ = s.Subscribe("acct-1", "plan-1", time.Now().UTC())
//	_, _ = s.RecordEvent(meter.Event{
//	    AccountID: "acct-1", EventID: "evt-1",
//	    At: time.Now().UTC(), Quantity: 120,
//	})
//
// 规则摘要：
//   - 金额与用量均为非负 int64，金额单位为分；税率为万分比且取值 [0,10000]。
//   - 账户、套餐标识唯一；缺失引用、负数或非法税率的请求失败且不改已有记录。
//   - 开通订阅时保存套餐条件快照，之后修改套餐不影响该订阅计费；每账户一份
//     当前有效订阅。
//   - 账期为 UTC 自然月，事件按发生时刻归期；时刻必须属于某段实际订阅期间
//     （开通时刻计入、终止时刻不计入），空档期间与晚于当前时刻的事件拒绝；
//     订阅终止后仍可补报旧订阅期间且尚未出账的用量。
//   - 事件/付款标识在账户内去重：完全相同的重报返回原结果（取消、重新开通后
//     亦然），关键信息不同报冲突。付款重报不再次登记，其返回的余额与付清状态
//     为该笔付款首次成功登记完成时的历史结果，不随后续付款或账单当前状态变化；
//     账单查询与账户状态中的余额始终反映当前状态。
//   - 已出账月份拒绝新事件（已接收事件的重报仍成功，到期欠费时新增仍拒绝）；
//     账单只能为某段订阅实际覆盖且已结束的月份生成，完全无订阅的空档月份出账
//     失败；重复出账得到同一张，金额与用量固定、付款状态可变。
//   - 可安排从下一个 UTC 自然月起换用另一套餐（升级、降级规则相同）：成功时锁定
//     目标套餐完整条件快照并返回生效账期；安排当月仍按旧套餐收完整月费、给完整
//     额度，不按天补差、不迁移用量。每账户至多一条待生效安排，同一目标重复安排
//     返回原安排不重新取价，另一目标则替换；生效前可取消，无安排时取消也成功。
//     到生效月月初零点自动生效，无需上报用量或出账；每张账单始终按该账期当时
//     适用的条件计费，历史账单不被后续切换覆盖。欠费停用期间可安排/取消但不
//     清欠、不解停，结清后按原规则恢复。
//   - 可登记按月取消订阅（CancelSubscription）：仅订阅已生效时可取消，欠费停用
//     不妨碍取消也不免除债务；终止时刻为请求时刻的下一个 UTC 自然月月初并在
//     结果中返回，当月仍按完整月费与额度计费、不按天退款。重复取消始终返回原
//     终止时刻不后移；生效前可用 UndoCancelSubscription 撤回（无取消安排时撤回
//     也成功），终止后撤回失败。登记取消会清除尚未生效的换套餐安排，等待取消
//     期间拒绝新的换套餐安排，撤回取消不恢复被清除的安排；恰在换套餐生效的
//     月初登记取消时，先承认该次切换，取消从再下一月生效。等待取消期间状态
//     仍显示有有效订阅并展示终止时刻；到达终止时刻即无有效订阅、无当前套餐与
//     待切换，历史用量与账单继续可查，且无需上报用量或生成账单。
//   - 终止后可通过原 Subscribe 入口重新开通：开通时刻不得早于上次终止时刻，
//     新订阅保存重新开通当时的套餐条件，当月仍收完整月费、给完整额度；有尚未
//     终止的订阅时拒绝再次开通。重新开通不重置账户内事件与付款标识、不清除旧
//     欠费；结清债务只解除欠费停用，不复活已取消的订阅。支持多次取消与重新
//     开通，旧月份的归属与计价不被后来订阅覆盖。
//   - 付款截止为账期结束后七天，支持分次付款；到期仍有余额则停用，结清后恢复。
//   - 用量或金额累计溢出 int64 时请求失败，不留下部分结果。
package meter

// Ready 表示基线可以运行。
func Ready() bool { return true }
